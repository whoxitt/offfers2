#!/usr/bin/env python3
"""Быстрый тест всех команд обхода peer_flood.

Выводит текст каждой команды для визуального осмотра.
"""

# Тестовые данные
SELLER = "TestUser"
NFT_NAME = "Party Sparkler"
NFT_NUMBER = "140864"
NFT_URL = "https://t.me/nft/PartySparkler-140864"
AMOUNT = "150 Gram"
TIME = "5ч 59м."

def print_test(test_name, description, text):
    """Вывести один тест."""
    print(f"\n{'='*80}")
    print(f"🧪 {test_name}")
    print(f"📝 {description}")
    print(f"{'-'*80}")
    print(text)
    print(f"{'='*80}")

# =============================================================================
# ТЕСТ1: БЕЗ слова "предлагает"
# =============================================================================
print_test(
    "ТЕСТ1 - без триггерного слова",
    "Полный оффер с таймером, но БЕЗ слова 'предлагает'",
    f"<b>{SELLER}</b> хочет купить у Вас <b>{AMOUNT}</b> за подарок "
    f"<a href=\"{NFT_URL}\">{NFT_NAME} #{NFT_NUMBER}</a>.\n\n"
    f"Это предложение активно ещё <b>{TIME}</b>"
)

# =============================================================================
# ТЕСТ2: Со словом "предлагает", БЕЗ таймера
# =============================================================================
print_test(
    "ТЕСТ2 - с триггером без таймера",
    "Есть 'предлагает' но нет фразы про активность (проверяем что именно триггерит)",
    f"<b>{SELLER}</b> предлагает Вам <b>{AMOUNT}</b> за подарок "
    f"<a href=\"{NFT_URL}\">{NFT_NAME} #{NFT_NUMBER}</a>."
)

# =============================================================================
# ТЕСТ3-1: Zero-width space
# =============================================================================
word = "пред\u200Bлагает"
print_test(
    "ТЕСТ3-1 - zero-width space",
    "Невидимый символ \\u200B между 'пред' и 'лагает'",
    f"<b>{SELLER}</b> {word} Вам <b>{AMOUNT}</b> за подарок "
    f"<a href=\"{NFT_URL}\">{NFT_NAME} #{NFT_NUMBER}</a>.\n\n"
    f"Это предложение активно ещё <b>{TIME}</b>"
)

# =============================================================================
# ТЕСТ3-2: Invisible separator
# =============================================================================
word = "предла\u2063гает"
